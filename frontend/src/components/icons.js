/** 按名称解析图标组件（也接受直接传入组件，便于渐进迁移）；未知名称返回 null */
export function resolveIcon(name) {
  if (!name) return null
  if (typeof name === 'object' || typeof name === 'function') return name
  return ICON_MAP[name] || null
}

