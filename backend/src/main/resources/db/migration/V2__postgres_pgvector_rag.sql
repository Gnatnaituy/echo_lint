-- ============================================================
-- V2：PostgreSQL + pgvector RAG 基础设施（Batch 6）
--
-- 背景：数据库从 MySQL 8 迁移到 PostgreSQL 17（pgvector 镜像）。
--   * Hibernate 仍以 ddl-auto: update 管理业务表（与 V1 约定一致）；
--   * 本迁移只负责「Hibernate 表达不了」的部分：
--       - vector 扩展
--       - knowledge_chunks 表（含 HNSW 表达式索引）
--       - 旧库升级时的增量列（新库由 Hibernate 建表，此处的 DO 块会自动跳过）
--
-- 注意：HNSW 索引维度写死 1536，必须与 app.rag.embedding.dimensions 一致。
--       更换 embedding 模型/维度时需要显式重建该索引（见 docs/rag-integration.md）。
-- ============================================================

CREATE EXTENSION IF NOT EXISTS vector;

-- 知识库条目的检索分块。向量以文本形式存储，索引用表达式把文本转成 vector：
-- Hibernate 无需自定义 UserType，读写都是 TEXT，检索走原生 SQL（CAST(? AS vector)）。
CREATE TABLE IF NOT EXISTS knowledge_chunks (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id       bigint       NOT NULL,
    chunk_index    integer      NOT NULL,
    content        text         NOT NULL,
    content_hash   varchar(64)  NOT NULL,
    embedding_text text,
    embedding_model varchar(128),
    embedding_dim  integer,
    created_at     timestamp(6) NOT NULL,
    updated_at     timestamp(6) NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_knowledge_chunks_entry_index
    ON knowledge_chunks (entry_id, chunk_index);
CREATE INDEX IF NOT EXISTS idx_knowledge_chunks_entry
    ON knowledge_chunks (entry_id);

-- 余弦距离 HNSW 索引；embedding_text 为 NULL 的行不会被索引。
CREATE INDEX IF NOT EXISTS idx_knowledge_chunks_hnsw
    ON knowledge_chunks USING hnsw ((embedding_text::vector(1536)) vector_cosine_ops);

-- ------------------------------------------------------------
-- 旧库升级（若表已存在）：新库在 Flyway 执行时业务表尚未创建，
-- 这些 DO 块会跳过，由 Hibernate 按实体建表。
-- ------------------------------------------------------------
DO $$
BEGIN
    IF to_regclass('public.knowledge_entries') IS NOT NULL THEN
        ALTER TABLE knowledge_entries ADD COLUMN IF NOT EXISTS source_type varchar(16) NOT NULL DEFAULT 'MANUAL';
        ALTER TABLE knowledge_entries ADD COLUMN IF NOT EXISTS source_filename varchar(255);
        ALTER TABLE knowledge_entries ADD COLUMN IF NOT EXISTS source_sha256 varchar(64);
        ALTER TABLE knowledge_entries ADD COLUMN IF NOT EXISTS source_size bigint;
        ALTER TABLE knowledge_entries ADD COLUMN IF NOT EXISTS index_status varchar(16) NOT NULL DEFAULT 'PENDING';
        ALTER TABLE knowledge_entries ADD COLUMN IF NOT EXISTS index_error text;
        ALTER TABLE knowledge_entries ADD COLUMN IF NOT EXISTS indexed_at timestamp(6);
        ALTER TABLE knowledge_entries ADD COLUMN IF NOT EXISTS embedding_hash varchar(64);
        ALTER TABLE knowledge_entries ADD COLUMN IF NOT EXISTS chunk_count integer NOT NULL DEFAULT 0;
    END IF;

    IF to_regclass('public.corpus_entries') IS NOT NULL THEN
        ALTER TABLE corpus_entries ADD COLUMN IF NOT EXISTS embedding_text text;
        ALTER TABLE corpus_entries ADD COLUMN IF NOT EXISTS embedding_model varchar(128);
        ALTER TABLE corpus_entries ADD COLUMN IF NOT EXISTS embedding_hash varchar(64);
        ALTER TABLE corpus_entries ADD COLUMN IF NOT EXISTS embedding_updated_at timestamp(6);
    END IF;

    IF to_regclass('public.ai_invocations') IS NOT NULL THEN
        ALTER TABLE ai_invocations ALTER COLUMN recording_id DROP NOT NULL;
    END IF;
END $$;
